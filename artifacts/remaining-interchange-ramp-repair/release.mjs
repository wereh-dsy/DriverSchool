import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
import {spawn} from 'node:child_process';
const dir='artifacts/remaining-interchange-ramp-repair/';
const read=f=>JSON.parse(fs.readFileSync(f,'utf8'));
assert.equal(read(dir+'build-result.json').exitCode,0);
assert(!fs.existsSync(dir+'release-started.json'),'Release already launched');
const startedAt=new Date().toISOString();
fs.writeFileSync(dir+'release-started.json',JSON.stringify({startedAt,command:'pnpm run desktop:package',includesAdditionalBrowserBuild:true},null,2));
const log=fs.createWriteStream(dir+'release.log');
let output='';
const child=spawn('powershell.exe',['-NoLogo','-NoProfile','-Command','pnpm run desktop:package'],{windowsHide:true,env:{...process.env,DRIVERSCHOOL_RELEASE_DIR:'D:/DriverSchoolRelease'},stdio:['ignore','pipe','pipe']});
for(const pipe of [child.stdout,child.stderr])pipe.on('data',chunk=>{output+=chunk.toString();log.write(chunk);process.stdout.write(chunk);});
const exitCode=await new Promise((resolve,reject)=>{child.once('error',reject);child.once('close',resolve);});
log.end();
const result={command:'pnpm run desktop:package',exitCode,startedAt,completedAt:new Date().toISOString(),browserBuildsThisBatch:2,browserBuildPublished:output.includes('Checkpoint published.'),log:dir+'release.log'};
fs.writeFileSync(dir+'release-result.json',JSON.stringify(result,null,2)+'\n');
assert.equal(exitCode,0,'Desktop package failed; see release.log');
await import('./verify-release.mjs');
