import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {spawn} from 'node:child_process';
const dir='artifacts/final-ramp-structural-cleanup/';
const read=f=>JSON.parse(fs.readFileSync(f,'utf8'));
const hash=b=>createHash('sha256').update(b).digest('hex');
const guard=read(dir+'scope-guard.json'),validation=read(dir+'validation.json'),baseline=read(dir+'baseline.json');
assert(guard.passed&&validation.passed&&validation.allRuntimePassed&&validation.allFacilitiesPassed&&validation.allCrossingsPassed&&validation.centralPassed);
assert.equal(validation.sourceHash,guard.candidateHash);
assert.equal(validation.counts.P0,0);assert.equal(validation.counts.P1,0);assert.equal(validation.counts.P2,0);
assert(!fs.existsSync(dir+'build-started.json'),'This batch build already started; inspect its result before retrying');
const source='src/world/regional/regional-main.json';
assert.equal(hash(fs.readFileSync(source)),guard.sourceHash,'Product baseline changed since validation');
assert.equal(hash(fs.readFileSync(dir+'candidate-map.json')),guard.candidateHash);
for(const [file,fingerprint] of Object.entries(baseline.physics))assert.equal(hash(fs.readFileSync(file)),fingerprint);
fs.copyFileSync(dir+'candidate-map.json',source);
assert.equal(hash(fs.readFileSync(source)),guard.candidateHash);
const startedAt=new Date().toISOString(),command='pnpm run build -BasicValidation';
fs.writeFileSync(dir+'build-started.json',JSON.stringify({startedAt,command,candidateHash:guard.candidateHash},null,2)+'\n');
const log=fs.createWriteStream(dir+'build.log');let output='';
const child=spawn('powershell.exe',['-NoLogo','-NoProfile','-Command',command],{windowsHide:true,stdio:['ignore','pipe','pipe']});
for(const stream of [child.stdout,child.stderr])stream.on('data',chunk=>{output+=chunk.toString();log.write(chunk);process.stdout.write(chunk);});
const exitCode=await new Promise((resolve,reject)=>{child.once('error',reject);child.once('close',resolve);});log.end();
const result={command,exitCode,startedAt,completedAt:new Date().toISOString(),browserBuildsThisBatch:1,published:output.includes('Checkpoint published.'),runtimeAsset:guard.expectedRuntimeAsset};
fs.writeFileSync(dir+'build-result.json',JSON.stringify(result,null,2)+'\n');assert.equal(exitCode,0,'Build failed; inspect build.log');
assert(result.published,'Build did not publish checkpoint');assert.equal(hash(fs.readFileSync('dist/'+guard.expectedRuntimeAsset)),guard.compiledRuntimeHash);
console.log('v492 Browser build and dist hash verified.');
